
import os
from contextlib import contextmanager

import psycopg
from psycopg.rows import dict_row


def get_database_url(database_url=None):
    """Get the PostgreSQL connection URL."""
    database_url = database_url or os.getenv("DATABASE_URL")

    if not database_url:
        raise ValueError(
            "DATABASE_URL is required. Configure your Neon connection URL."
        )

    if not database_url.startswith(("postgresql://", "postgres://")):
        raise ValueError(
            "Only PostgreSQL is supported. Provide a valid PostgreSQL URL."
        )

    return database_url


@contextmanager
def get_connection(database_url=None):
    """Open and safely close a PostgreSQL connection."""
    database_url = get_database_url(database_url)

    connection = psycopg.connect(
        database_url,
        row_factory=dict_row,
    )

    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def init_db(database_url=None):
    """Create the applications table if it does not exist."""
    query = """
        CREATE TABLE IF NOT EXISTS applications (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            company_name TEXT NOT NULL,
            job_role TEXT NOT NULL,
            application_date TEXT NOT NULL,
            status TEXT NOT NULL CHECK (
                status IN (
                    'Applied',
                    'Online Assessment',
                    'Interview',
                    'Selected',
                    'Rejected'
                )
            ),
            job_url TEXT NOT NULL DEFAULT '',
            notes TEXT NOT NULL DEFAULT '',
            follow_up_date TEXT NULL,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
    """

    with get_connection(database_url) as connection:
        connection.execute(query)
